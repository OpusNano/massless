//! Renders the site at build time, pre-compresses every response and
//! generates the route table.

#[allow(dead_code)]
#[path = "src/render.rs"]
mod render;

use std::{env, fmt::Write, fs, path::Path, process::exit};

fn main() {
    for p in ["posts", "templates", "src/render.rs"] {
        println!("cargo:rerun-if-changed={p}");
    }
    println!("cargo:rerun-if-env-changed=SITE_URL");

    let site_url = env::var("SITE_URL").unwrap_or_default();
    let site = render::load(Path::new("posts"), Path::new("templates"))
        .and_then(|input| render::render(&input, site_url.trim_end_matches('/')))
        .unwrap_or_else(|e| {
            eprintln!("error: massless: {e}");
            exit(1)
        });

    let out = env::var("OUT_DIR").expect("OUT_DIR");
    let out = Path::new(&out);

    let mut rs = String::from("/// Path -> page, sorted by path (generated by build.rs).\n");
    rs += "pub static PAGES: &[(&str, Page)] = &[\n";
    for (i, p) in site.pages.iter().enumerate() {
        let page = page_rs(out, &format!("page{i}"), p.content_type, &p.body);
        writeln!(rs, "    ({:?}, {page}),", p.path).unwrap();
    }
    rs += "];\n\n";
    let page = page_rs(out, "not_found", render::HTML, &site.not_found);
    writeln!(rs, "pub static NOT_FOUND: Page = {page};").unwrap();
    fs::write(out.join("site.rs"), rs).expect("write site.rs");
}

/// Writes the identity body and its gzip/brotli variants to `out` and returns
/// a `Page` expression. A compressed variant is kept only if it is smaller.
fn page_rs(out: &Path, name: &str, content_type: &str, body: &[u8]) -> String {
    let hash = fnv1a(body);
    let variant = |suffix: &str, bytes: &[u8]| {
        let path = out.join(format!("{name}{suffix}"));
        fs::write(&path, bytes).expect("write page");
        format!(
            "Variant {{ body: include_bytes!({:?}), etag: {:?} }}",
            path.display().to_string(),
            format!("\"{hash:016x}{suffix}\"")
        )
    };
    let smaller = |suffix: &str, bytes: Vec<u8>| {
        if bytes.len() < body.len() {
            format!("Some({})", variant(suffix, &bytes))
        } else {
            "None".into()
        }
    };
    format!(
        "Page {{ content_type: {content_type:?}, identity: {}, gzip: {}, br: {} }}",
        variant("", body),
        smaller("-gz", gzip(body)),
        smaller("-br", brotli(body)),
    )
}

fn gzip(data: &[u8]) -> Vec<u8> {
    let mut out = Vec::new();
    zopfli::compress(
        zopfli::Options::default(),
        zopfli::Format::Gzip,
        data,
        &mut out,
    )
    .expect("gzip");
    out
}

fn brotli(data: &[u8]) -> Vec<u8> {
    let params = brotli::enc::BrotliEncoderParams {
        quality: 11,
        lgwin: 22,
        size_hint: data.len(),
        ..Default::default()
    };
    let mut out = Vec::new();
    brotli::BrotliCompress(&mut &data[..], &mut out, &params).expect("brotli");
    out
}

/// 64-bit FNV-1a: a stable content hash for ETags.
fn fnv1a(data: &[u8]) -> u64 {
    data.iter().fold(0xcbf2_9ce4_8422_2325, |h, &b| {
        (h ^ u64::from(b)).wrapping_mul(0x0000_0100_0000_01b3)
    })
}
