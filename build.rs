//! Renders the site at build time and generates the route table.

#[allow(dead_code)]
#[path = "src/render.rs"]
mod render;

use std::{env, fmt::Write, fs, path::Path, process::exit};

fn main() {
    for p in ["posts", "templates", "src/render.rs"] {
        println!("cargo:rerun-if-changed={p}");
    }
    println!("cargo:rerun-if-env-changed=SITE_URL");

    let site_url = env::var("SITE_URL").unwrap_or_default();
    let site = render::load(Path::new("posts"), Path::new("templates"))
        .and_then(|input| render::render(&input, site_url.trim_end_matches('/')))
        .unwrap_or_else(|e| {
            eprintln!("error: massless: {e}");
            exit(1)
        });

    let out = env::var("OUT_DIR").expect("OUT_DIR");
    let out = Path::new(&out);
    let embed = |name: &str, body: &[u8]| {
        let path = out.join(name);
        fs::write(&path, body).expect("write page");
        format!("include_bytes!({:?})", path.display().to_string())
    };

    let mut rs = String::from("/// Path -> page, sorted by path (generated by build.rs).\n");
    rs += "pub static PAGES: &[(&str, Page)] = &[\n";
    for (i, p) in site.pages.iter().enumerate() {
        let body = embed(&format!("page{i}"), &p.body);
        writeln!(
            rs,
            "    ({:?}, Page {{ content_type: {:?}, body: {body} }}),",
            p.path, p.content_type
        )
        .unwrap();
    }
    rs += "];\n\n";
    writeln!(
        rs,
        "pub static NOT_FOUND: Page = Page {{ content_type: {:?}, body: {} }};",
        render::HTML,
        embed("not_found", &site.not_found)
    )
    .unwrap();
    fs::write(out.join("site.rs"), rs).expect("write site.rs");
}
